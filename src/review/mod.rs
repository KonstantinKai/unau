#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Kind {
    Fix,
    Question,
    Suggestion,
}

impl Kind {
    pub fn name(self) -> &'static str {
        match self {
            Self::Fix => "fix",
            Self::Question => "question",
            Self::Suggestion => "suggestion",
        }
    }

    pub fn from_name(name: &str) -> Option<Self> {
        match name {
            "fix" => Some(Self::Fix),
            "question" => Some(Self::Question),
            "suggestion" => Some(Self::Suggestion),
            _ => None,
        }
    }
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Status {
    #[default]
    Open,
    /// An agent has started on the review.
    InProgress,
    Partial,
    Done,
}

impl Status {
    pub fn name(self) -> &'static str {
        match self {
            Self::Open => "open",
            Self::InProgress => "in-progress",
            Self::Partial => "partial",
            Self::Done => "done",
        }
    }

    pub fn from_name(name: &str) -> Option<Self> {
        match name {
            "open" => Some(Self::Open),
            "in-progress" | "in_progress" => Some(Self::InProgress),
            "partial" => Some(Self::Partial),
            "done" => Some(Self::Done),
            _ => None,
        }
    }
}

/// What an item is attached to.
#[derive(Clone, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Scope {
    General,
    File(String),
    /// New-side lines `start..=end`. `removed` marks a selection of removed
    /// lines only: they sit just before new-side line `start`, and `start == end`.
    Lines {
        path: String,
        start: usize,
        end: usize,
        removed: bool,
    },
}

impl Scope {
    pub fn path(&self) -> Option<&str> {
        match self {
            Self::General => None,
            Self::File(path) | Self::Lines { path, .. } => Some(path),
        }
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Item {
    pub done: bool,
    /// Marked `[~]`: an agent is working on it. Still open.
    pub working: bool,
    pub kind: Kind,
    pub scope: Scope,
    pub text: String,
    /// Language tag of the code fences: the file extension, or empty.
    pub lang: String,
    /// Exact anchored lines at write time (removed lines for removed scopes);
    /// for a long quote only its first and last lines, see `elided`.
    pub quote: Vec<String>,
    /// Lines left out of the middle of `quote`, when it was capped.
    pub elided: Option<Elision>,
    /// Replacement lines of a suggestion.
    pub replacement: Option<Vec<String>>,
    /// Lines under the item the tool does not understand, kept verbatim.
    pub extra: Vec<String>,
}

impl Item {
    pub fn new(kind: Kind, scope: Scope, text: String) -> Self {
        let lang = scope
            .path()
            .and_then(|p| Path::new(p).extension())
            .and_then(|e| e.to_str())
            .unwrap_or_default()
            .to_owned();
        Self {
            done: false,
            working: false,
            kind,
            scope,
            text,
            lang,
            quote: Vec::new(),
            elided: None,
            replacement: None,
            extra: Vec::new(),
        }
    }

    /// Sets the quoted lines, keeping only the first and last few when there
    /// are more than `max` (0 means no limit). The agent reads the file anyway;
    /// the kept lines are enough to find the place again.
    pub fn set_quote(&mut self, lines: Vec<String>, max: usize) {
        let edge = QUOTE_EDGE_LINES.min(max / 2).max(1);
        if max == 0 || lines.len() <= max {
            self.quote = lines;
            self.elided = None;
            return;
        }
        let count = lines.len() - 2 * edge;
        let mut kept = lines;
        kept.drain(edge..edge + count);
        self.quote = kept;
        self.elided = Some(Elision { at: edge, count });
    }

    /// How many lines the quote stood for, left-out ones included.
    pub fn quote_len(&self) -> usize {
        self.quote.len() + self.elided.map_or(0, |e| e.count)
    }

    /// Sort key that gives the order items are written in.
    fn order(&self) -> (u8, &str, u8, usize) {
        match &self.scope {
            Scope::General => (0, "", 0, 0),
            Scope::Lines { path, start, .. } => (1, path, 0, *start),
            Scope::File(path) => (1, path, 1, 0),
        }
    }
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Review {
    pub tool: String,
    pub status: Status,
    pub base: String,
    /// Blob id per annotated file at review time.
    pub files: BTreeMap<String, String>,
    /// `YYYY-MM-DD-NN`.
    pub name: String,
    /// Agent instructions, Markdown, as written into this review.
    pub instructions: String,
    pub items: Vec<Item>,
    /// Lines outside any item the tool does not understand, kept verbatim.
    pub extra: Vec<String>,
}

impl Review {
    pub fn new(name: &str, base: &str) -> Self {
        Self {
            tool: format!("unau {}", env!("CARGO_PKG_VERSION")),
            status: Status::Open,
            base: base.to_owned(),
            files: BTreeMap::new(),
            name: name.to_owned(),
            instructions: DEFAULT_INSTRUCTIONS.to_owned(),
            items: Vec::new(),
            extra: Vec::new(),
        }
    }

    /// Puts items in written order, so a parsed file equals its source.
    pub fn normalize(&mut self) {
        self.items.sort_by(|a, b| a.order().cmp(&b.order()));
    }

    /// Open items an agent has marked `[~]`.
    pub fn working_items(&self) -> usize {
        self.items.iter().filter(|i| i.working && !i.done).count()
    }

    pub fn open_items(&self) -> usize {
        self.items.iter().filter(|i| !i.done).count()
    }

    pub fn is_empty(&self) -> bool {
        self.items.is_empty()
    }
}

/// The newest review in `dir`: the highest date, then the highest number,
/// compared as a number so `-100` comes after `-99`. Other files are ignored.
pub fn latest(dir: &Path) -> Option<std::path::PathBuf> {
    let entries = std::fs::read_dir(dir).ok()?;
    entries
        .filter_map(Result::ok)
        .filter_map(|entry| {
            let name = entry.file_name().to_str()?.strip_suffix(".md")?.to_owned();
            let (date, number) = name.rsplit_once('-')?;
            let number: u64 = number.parse().ok()?;
            let valid_date = date.len() == 10
                && date.chars().enumerate().all(|(i, c)| {
                    if i == 4 || i == 7 {
                        c == '-'
                    } else {
                        c.is_ascii_digit()
                    }
                });
            valid_date.then(|| ((date.to_owned(), number), entry.path()))
        })
        .max_by(|a, b| a.0.cmp(&b.0))
        .map(|(_, path)| path)
}

/// `YYYY-MM-DD-NN` for the first file name not yet taken in `dir` on `date`.
/// Numbers start at `00` and widen past `99`.
pub fn next_name(dir: &Path, date: &str) -> String {
    let taken = |n: usize| dir.join(format!("{date}-{n:02}.md")).exists();
    let n = (0..usize::MAX).find(|n| !taken(*n)).unwrap_or(0);
    format!("{date}-{n:02}")
}

/// Today's local date as `YYYY-MM-DD`.
pub fn today() -> String {
    jiff::Zoned::now().date().to_string()
}

pub fn load(path: &Path) -> Result<(Review, String)> {
    let text = std::fs::read_to_string(path)?;
    Ok((parse(&text)?, text))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn long_quotes_keep_their_first_and_last_lines() {
        let lines: Vec<String> = (1..=20).map(|n| n.to_string()).collect();
        let mut item = Item::new(Kind::Fix, Scope::General, String::new());
        item.set_quote(lines.clone(), 12);
        assert_eq!(item.quote, ["1", "2", "3", "18", "19", "20"]);
        assert_eq!(item.elided, Some(Elision { at: 3, count: 14 }));
        assert_eq!(item.quote_len(), 20);
        item.set_quote(lines.clone(), 4);
        assert_eq!(item.quote, ["1", "2", "19", "20"]);
        item.set_quote(lines.clone(), 0);
        assert_eq!((item.quote.len(), item.elided), (20, None));
        item.set_quote(lines[..12].to_vec(), 12);
        assert_eq!((item.quote.len(), item.elided), (12, None));
        assert_eq!(Elision { at: 3, count: 14 }.marker(), "⋯ 14 more lines ⋯");
        assert_eq!(Elision::parse_marker("⋯ 1 more line ⋯"), Some(1));
        assert_eq!(Elision::parse_marker("// ⋯ not a marker"), None);
    }

    #[test]
    fn latest_picks_the_newest_date_then_the_highest_number() {
        let dir = tempfile::tempdir().unwrap();
        assert_eq!(latest(dir.path()), None);
        for name in [
            "2026-10-13-07.md",
            "2026-10-14-02.md",
            "2026-10-14-99.md",
            "2026-10-14-100.md",
            "instructions.md",
            "2026-10-15-notes.md",
            "2026-10-16-00.txt",
        ] {
            std::fs::write(dir.path().join(name), "").unwrap();
        }
        assert_eq!(
            latest(dir.path()),
            Some(dir.path().join("2026-10-14-100.md"))
        );
        assert_eq!(latest(&dir.path().join("missing")), None);
    }

    #[test]
    fn next_name_takes_the_first_free_number_and_widens_past_99() {
        let dir = tempfile::tempdir().unwrap();
        assert_eq!(next_name(dir.path(), "2026-10-14"), "2026-10-14-00");
        for n in 0..100 {
            std::fs::write(dir.path().join(format!("2026-10-14-{n:02}.md")), "").unwrap();
        }
        assert_eq!(next_name(dir.path(), "2026-10-14"), "2026-10-14-100");
        assert_eq!(next_name(dir.path(), "2026-10-15"), "2026-10-15-00");
    }

    #[test]
    fn language_tag_comes_from_the_extension() {
        let item = Item::new(Kind::Fix, Scope::File("src/a.ts".into()), String::new());
        assert_eq!(item.lang, "ts");
        let item = Item::new(Kind::Fix, Scope::File("Makefile".into()), String::new());
        assert_eq!(item.lang, "");
    }
}
