/// Instructions written into a review when no instructions file says otherwise.
pub const DEFAULT_INSTRUCTIONS: &str = "\
- Before you start, set `status: in-progress`.
- Work through every unchecked item. Before working on one, mark it `[~]`, so the reviewer can follow along; mark it `[x]` only when the change is made and tests pass.
- Anchors such as `:42-48` are line numbers in the current file. If they have drifted, trust the quoted lines, not the numbers.
- `question` items: answer in a line under the item and tick it; change code only if the answer calls for it.
- `suggestion` items: apply the replacement as written; if it would break something, say why under the item instead.
- Never stage or commit. Do not edit this file beyond `[~]` and `[x]` marks, notes under items, and `status`.
- When you finish, set `status: done` if every item is ticked, else `partial`.";

/// Lines kept at each end of a capped quote.
pub const QUOTE_EDGE_LINES: usize = 3;

/// Default for `[review] quote_lines`: longer quotes are capped.
pub const DEFAULT_QUOTE_LINES: usize = 12;

/// Lines left out of a capped quote: `count` lines after the first `at`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Elision {
    pub at: usize,
    pub count: usize,
}

impl Elision {
    /// The line written in place of the left-out lines.
    pub fn marker(self) -> String {
        let lines = if self.count == 1 { "line" } else { "lines" };
        format!("⋯ {} more {lines} ⋯", self.count)
    }

    /// Reads a marker line back.
    pub fn parse_marker(line: &str) -> Option<usize> {
        let inner = line.trim().strip_prefix("⋯ ")?.strip_suffix(" ⋯")?;
        let count = inner
            .strip_suffix(" more lines")
            .or_else(|| inner.strip_suffix(" more line"))?;
        count.parse().ok()
    }
}

